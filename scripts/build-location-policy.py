"""Bundle the current display reference for advisory location QA, never authorisation.

Run after changing the reference overlay. --check detects stale packaged copies.
No GIS runtime or network is required; no distances/areas are calculated.
"""
import argparse
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    match = re.search(r'const zonaRegableData = (.*);', (ROOT / 'index.html').read_text())
    reference = json.loads(match[1])['features'][0]
    metadata = json.loads((ROOT / 'data/sentinel-aoi.json').read_text())
    assert reference['geometry']['type'] == 'Polygon'
    assert reference['properties']['status'] == 'pending_adjustment'
    policy = {
        'version': '1', 'crs': 'EPSG:4326', 'status': 'pending_adjustment',
        'source': 'index.html:zonaRegableData (display simplified from ZR.gml)',
        'source_sha256': metadata['source_sha256'],
        'bbox': metadata['catalog_bbox']['bounds'],
        'far_margin_degrees': 0.15, 'gps_warning_m': 50,
        'geometry': reference['geometry'],
    }
    compact = json.dumps(policy, ensure_ascii=False, separators=(',', ':'))
    files = {
        'wordpress/castrejon-averias/location-policy.json': compact + '\n',
        'averias/location-policy.js': '// Generated by scripts/build-location-policy.py; do not edit.\n'
        '(function(root){const policy=' + compact + ';\n'
        "if(typeof module!=='undefined')module.exports=policy;else root.CastrejonLocationPolicy=policy;})(globalThis);\n",
    }
    for name, content in files.items():
        path = ROOT / name
        if args.check:
            if not path.exists() or path.read_text() != content:
                raise SystemExit('Stale location policy: run python scripts/build-location-policy.py')
        else:
            path.write_text(content)


if __name__ == '__main__':
    main()
